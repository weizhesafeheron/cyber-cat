/**
 * 逗猫的全部可调数值。
 *
 * **集中在一个文件里是票上的硬要求**（issue #11：「所有阈值必须做成可调配置，
 * 开发期取保守值，真机使用数天后再定档」）。所以这里的每个值都还没定档 -
 * 注释里写的是「为什么取这个量级」，不是「这个值是对的」。
 *
 * 取值一律偏保守（宁可猫少反应）。理由不对称：漏掉一次邀请，用户只是没注意到；
 * 多响应一次，用户正在做的事被打断。桌面宠物的失效方向必须是「安静」。
 */

/** 光标进入这个半径（CSS 像素）才算进了猫的注意范围。 */
export const NOTICE_RADIUS_PX = 180;

/**
 * 光标速度下限，CSS 像素每秒。慢过它的移动不算邀请。
 *
 * 用户把光标平移去点某个按钮的速度通常在 300 到 800；真的在逗猫时会甩得更快、
 * 而且会来回。取 520 是「明显比日常操作快」的量级，配合下面的方向变化一起判定 -
 * 单看速度会把「快速划过屏幕去点右上角」误判成逗猫。
 */
export const PREY_SPEED_MIN = 520;

/**
 * 方向变化的下限，弧度。
 *
 * 这是「像猎物」的核心：猎物是**乱动**的，而用户的正常操作是直线。
 * 0.9 弧度约 52 度 - 直线移动的抖动远小于它，而来回甩必然超过。
 */
export const PREY_TURN_MIN = 0.9;

/** 判定运动特征要看最近这么长的一段轨迹，毫秒。 */
export const PREY_WINDOW_MS = 420;

/** 这段轨迹里至少要有这么多个采样点，否则数据不足、一律不算邀请。 */
export const PREY_MIN_SAMPLES = 4;

/**
 * 键盘活跃的判定：距上次按键短于这么多秒就算「用户在打字」，完全无视光标。
 *
 * 2 秒是打字的自然间隙：句子之间的停顿通常短于它，而「打完字去动鼠标」通常长于它。
 *
 * Windows 上这个数的语义更粗（见 platform 层的注释）：那边拿到的是「距上次任何
 * 输入」，所以键盘与鼠标都算。失效方向仍然是安全的 - 猫更安静。
 */
export const TYPING_IDLE_S = 2;

/** 心情低于此值不理光标。心情差的猫不想玩，这是「状态闸门」的一部分。 */
export const MOOD_MIN_TO_PLAY = 35;

/**
 * 刚吃饱之后犯困，这段时间里不理光标（毫秒）。
 *
 * 真猫饭后就是要趴一会儿。这条也顺带避免了一个难看的画面：
 * 猫刚走到食盆吃上饭，光标一晃它就丢下饭去追。
 */
export const DROWSY_AFTER_MEAL_MS = 90_000;

/** 饱食度高于此值算「刚吃饱」。与犯困那条一起用。 */
export const FULL_ENOUGH = 85;

/**
 * 连续扑中几次之后玩腻。
 *
 * 票上写的是 3 到 4 次，取 3 - 少一次比多一次安全。
 */
export const BORED_AFTER_POUNCES = 3;

/** 玩腻之后的冷却时长，毫秒。票上写「数分钟」，取 4 分钟。 */
export const BORED_COOLDOWN_MS = 240_000;

/**
 * 两次扑跳之间的最小间隔，毫秒。
 *
 * 与玩腻机制不是一回事：这条防的是「同一次挥动光标里连着扑好几下」。
 */
export const POUNCE_GAP_MS = 6_000;

/**
 * 每小时主动追逐的次数上限，按活跃度插值。
 *
 * 懒猫 4 次、最活跃的猫 12 次。**这是全局节流**，玩腻机制之外的第二道保险：
 * 玩腻只管连续扑中，而一整天零散地扑上百次同样是骚扰。
 */
export const CHASES_PER_HOUR_LAZY = 4;
export const CHASES_PER_HOUR_ACTIVE = 12;

/** 全局节流的统计窗口，毫秒。 */
export const CHASE_WINDOW_MS = 3_600_000;

/**
 * 落点离光标多远，CSS 像素。
 *
 * **不扑到光标上**（票上的硬要求）：猫停在光标旁边，不压住用户要点的位置。
 * 60 是「明显在旁边但仍然算扑向它」的量级 - 猫本体有 216 像素宽，
 * 落点再远就看不出是在追这个光标了。
 */
export const POUNCE_OFFSET_PX = 60;

/**
 * 反应快慢的性格缩放：从「注意到」到「起跳」等多久，毫秒。
 *
 * 懒猫慢半拍，活跃的猫说走就走。票上要求「响应节奏由性格缩放，不是全局常量」。
 */
export const REACT_DELAY_LAZY_MS = 900;
export const REACT_DELAY_ACTIVE_MS = 180;
