import { CHROME_H } from '../chrome/constants.js';
import { H, W } from '../render/index.js';

/**
 * 猫咪日记与回归气泡的可调数值。
 *
 * 阈值本身（离开多久才冒气泡）在 world/constants.ts 的 DIARY_BUBBLE_AWAY_HOURS -
 * 那是产品规则，和每日条数上限是同一族的东西。这里只放呈现层的数：气泡多大、
 * 画在哪、日记窗口多大。
 */

// ---------------------------------------------------------------------------
// 回归气泡
// ---------------------------------------------------------------------------

/**
 * 气泡尺寸，精灵像素。
 *
 * 22×18 在 3 倍缩放下是 66×54 CSS 像素。**下限由「点得中」定，不由好看定**：
 * 气泡是这一版里唯一一个需要精确点击的小目标，比它再小就要靠命中边距来救，
 * 而边距是会偷用户点击的窄带（见 app/hit.ts 的 baseMargin）。
 */
export const BUBBLE_W_SPRITE = 22;
export const BUBBLE_H_SPRITE = 18;

/**
 * 气泡下沿（尾巴尖）落在精灵缓冲的第几行。
 *
 * 5 是量出来的，不是估的：把七个品种、每个五颗种子、全部动作逐帧渲染一遍，
 * 猫本体最靠上的像素落在第 7 行（扑跳腾空时）。取 5 留两行空隙，于是气泡
 * **在任何姿态下都不会压到猫**，也不需要每帧去问「今天的头顶在哪」。
 *
 * 被否决的方案是「跟着头部锚点走」（渲染层的 anchors.hy）：头部锚点每帧都在动，
 * 气泡会跟着抖；而且趴下、睡觉、吃饭时头会低到第 21 行，气泡跟下去就钻进猫身上了。
 */
export const BUBBLE_BASE_SPRITE_Y = 5;

/** 气泡横向居中于精灵。锚点是精灵中心，所以气泡跟着猫走是结构保证的。 */
export const BUBBLE_X0_SPRITE = Math.round((W - BUBBLE_W_SPRITE) / 2);

/**
 * 上下浮动的幅度与周期。
 *
 * 幅度只有 1 个精灵像素、且取整：非整数偏移会让整块气泡在物理像素上重采样，
 * 像素风当场破功（与 display.ts 的取整是同一条约束）。
 * 浮动是气泡「要人点它」的唯一提示 - 完全静止的小方块在桌面上会被读成装饰。
 */
export const BUBBLE_BOB_SPRITE = 1;
export const BUBBLE_BOB_PERIOD_S = 2.2;

/**
 * 气泡在头顶待多久就自己收掉，毫秒。
 *
 * **不设期限是不行的。** 气泡是一块 66×54 CSS 像素的可点区域，而它跟着猫在整个桌面上
 * 走；用户不理它的话，那块区域会一直在猫头顶偷走点击（穿透是整窗一刀切的，ADR 0006）。
 * 「不拦用户」这条要求包含「不理它它就该消失」。
 *
 * 三分钟的取法：一次会话本来就是「看一眼」的量级（CONTEXT.md 的真实时间），
 * 三分钟够注意到头顶多了个东西，又短到不会变成常驻噪音。
 * 错过了也没关系 - 日记的常驻入口在托盘菜单里，气泡只是提示。
 */
export const BUBBLE_LIFE_MS = 180_000;

/**
 * 气泡需要的舞台净空，精灵像素。
 *
 * = 气泡整体在精灵缓冲**之上**伸出去多少。舞台高度必须容得下
 * 「猫的画布 + 这段净空」，否则气泡会被窗口边缘裁掉。
 * test/diary/bubble.test.ts 用各档真实 dpr 守着这条。
 */
export const BUBBLE_HEADROOM_SPRITE =
  BUBBLE_H_SPRITE + BUBBLE_BOB_SPRITE - BUBBLE_BASE_SPRITE_Y;

/** 气泡整体高度（含浮动余量）在精灵缓冲里占的行数。画布尺寸的校验用。 */
export const BUBBLE_SPAN_SPRITE = BUBBLE_HEADROOM_SPRITE + BUBBLE_BASE_SPRITE_Y;

/** 精灵缓冲高度。换算「精灵 y → 舞台内 y」时要用，导出省得调用方再 import 渲染层。 */
export const SPRITE_H = H;

// ---------------------------------------------------------------------------
// 日记窗口
// ---------------------------------------------------------------------------

/**
 * 日记窗口尺寸，逻辑像素。
 *
 * 竖长条：日记是一列按天分组的短句，宽了之后每行只占左边一小截，读起来更累。
 * 高度给到 560 是为了「一屏能看到两三天」- 一屏只有一天的话翻页感太强，
 * 而日记的价值恰恰在于连着看下来像一段生活。
 */
export const DIARY_W = 420;
export const DIARY_H = 560;

/**
 * 缩放的下限，逻辑像素（含自绘标题条那 28）。
 *
 * 宽度 360 是「每行不断成两三截」的下限：日记条目左边有一列 40 宽的时刻，
 * 再窄下去正文只剩不到 300，中文一行放不下一句完整的话。
 * 高度 320 只是「还看得见一条」的下限 - 拉到这么小的人是想把它当便签摆在角上。
 *
 * 这两个数会一路传到 Rust 的 min_inner_size（open_diary 的参数），
 * 右下角把手也钳同一对（src/chrome/resize.ts）。**只有这一份。**
 */
export const DIARY_MIN_W = 360;
export const DIARY_MIN_H = 320 + CHROME_H;

/**
 * 界面上最多显示多少条。
 *
 * 存档里最多 400 条（DIARY_MAX_ENTRIES），全渲染出来也不过 400 个 DOM 节点，
 * 所以这个上限不是为了性能，是为了**先看到最近的**：日记按倒序分组显示，
 * 早年的条目在最下面，真要一次全铺出来滚动条会长得没有参考意义。
 */
export const DIARY_VISIBLE_ENTRIES = 200;
