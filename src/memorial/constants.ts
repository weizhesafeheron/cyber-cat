/**
 * 猫的档案的可调数值。
 *
 * 与 props/constants.ts 同一条纪律：档案有自己的存档版本，**不跟着 WORLD_VERSION 走**。
 * 两份文件的结构各自独立演化，共用一个版本号会让改了世界结构就必须丢掉整份档案 -
 * 而档案是全局唯一不可再生的数据（那些猫都死了，没法重新演化出来）。
 */

/** 档案存档格式版本。结构变更时递增。 */
export const MEMORIAL_SAVE_VERSION = 1;

/**
 * 档案里最多留这么多只猫，超出丢最早的。
 *
 * 「档案保留历任猫」是产品要求，这个上限只是防止文件无限膨胀的安全阀：
 * 一只猫的日记上限 400 条（DIARY_MAX_ENTRIES），一条约 60 字节，
 * 50 只猫大约 1.2MB - 而按每只猫活几周算，50 只是好几年的事。
 * 真到那时候丢掉最早的一只，也比某天读一个几十兆的 JSON 好。
 */
export const MEMORIAL_MAX_CATS = 50;
