/**
 * 自绘标题栏的可调数值。
 *
 * 三扇弹出窗口（领养、日记、告别）都不要系统标题栏了：
 * macOS 那条灰色渐变条压在深蓝雨夜上面，和页面配色完全断开。
 * 取舍与两个平台的坑写在 docs/adr/0013-自绘标题栏.md，改这里之前先读一遍。
 */

/**
 * 标题条高度，CSS 逻辑像素。
 *
 * 28 而不是系统那 30：像素风的条子矮一点更像一条边框而不是一块面板。
 * **这个数只在这里有一份。** 三个页面的 CSS 用 `var(--chrome-h)`，
 * 由 mountChrome 写进 CSS 变量；窗口高度用 `withChrome()` 把它加上去。
 * 散成两份的话，条子和内容会在某一次调整之后差出几像素，而这种差错只在真机上看得见。
 */
export const CHROME_H = 28;

/**
 * 右下角缩放把手的边长，CSS 逻辑像素。
 *
 * 14 是「点得中」的下限：它是一个需要精确按住的小目标，
 * 比它再小就要靠命中边距来救（与回归气泡同一条经验，见 diary/constants.ts）。
 */
export const GRIP_H = 14;

/**
 * 无边框窗口下**内容区就是整扇窗**，所以窗口高度要把标题条算进去。
 *
 * 之前系统标题栏在客户区之外：`inner_size` 给 468，窗口总高是 468 + 30。
 * 现在标题条画在客户区里面，不加这一段的话内容会被压掉 28 像素 -
 * 领养页 overflow 是 hidden，被压掉的正好是最后那行提示。
 */
export function withChrome(contentH: number): number {
  return contentH + CHROME_H;
}
